package com.interview.agent.memory;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import jakarta.annotation.PostConstruct;
import org.springframework.context.annotation.Profile;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

/** H2-backed persistent storage for the local profile. */
@Component
@Profile("local")
public class LocalMySQLStore extends MySQLStore {
    private final JdbcTemplate jdbc;
    private final ObjectMapper mapper = new ObjectMapper().registerModule(new JavaTimeModule());

    public LocalMySQLStore(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    @PostConstruct
    public void migrate() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS user_profiles (
                    user_id VARCHAR(128) PRIMARY KEY,
                    name VARCHAR(256) DEFAULT '',
                    skill_level VARCHAR(1000000),
                    weak_points VARCHAR(1000000),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS interview_records (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id VARCHAR(128) NOT NULL,
                    session_id VARCHAR(128) NOT NULL UNIQUE,
                    position VARCHAR(256) DEFAULT '',
                    overall_score DOUBLE DEFAULT 0,
                    report_json VARCHAR(1000000),
                    review_plan_json VARCHAR(1000000),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_interview_records_user ON interview_records(user_id)");
    }

    @Override
    @Transactional
    public void saveProfile(UserProfile profile) {
        try {
            String skills = mapper.writeValueAsString(profile.getSkillLevel());
            String weakPoints = mapper.writeValueAsString(profile.getWeakPoints());
            int changed = jdbc.update("""
                    UPDATE user_profiles SET name=?, skill_level=?, weak_points=?, updated_at=CURRENT_TIMESTAMP
                    WHERE user_id=?
                    """, profile.getName() == null ? "" : profile.getName(), skills, weakPoints, profile.getUserId());
            if (changed == 0) {
                jdbc.update("INSERT INTO user_profiles(user_id,name,skill_level,weak_points) VALUES(?,?,?,?)",
                        profile.getUserId(), profile.getName() == null ? "" : profile.getName(), skills, weakPoints);
            }
        } catch (Exception e) {
            throw new IllegalStateException("Unable to save local profile", e);
        }
    }
}
